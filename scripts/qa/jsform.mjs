const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
const p = await browser.newPage();
const logs = [];
p.on("console", (m) => (m.type() === "error" || m.type() === "warning") && logs.push(m.text()));
const posts = [];
p.on("request", (r) => r.method() === "POST" && posts.push(`${r.url().replace("http://localhost:3000", "")} ${r.headers()["content-type"]}`));
await p.goto("http://localhost:3000/#demo", { waitUntil: "networkidle" });
console.log("step 2 hidden with JS:", !(await p.locator("#demo-business").isVisible()));
console.log("form novalidate with JS:", await p.locator("#demo form").getAttribute("novalidate"));
await p.fill("#demo-name", "Jay Script");
await p.fill("#demo-email", "jay@example.com");
await p.getByRole("button", { name: "Next: About Your Business" }).click();
await p.fill("#demo-business", "Script Cafe");
await p.fill("#demo-phone", "(555) 123-4567");
await p.selectOption("#demo-industry", { index: 1 });
await p.getByRole("button", { name: "Get My Free Demo" }).last().click();
await p.getByText("Got it. Your free demo is in the works.").waitFor();
console.log("inline success, url:", new URL(p.url()).pathname + new URL(p.url()).hash, "| posts:", posts.join(" ; "));
await p.goto("http://localhost:3000/#contact", { waitUntil: "networkidle" });
await p.fill("#contact-name", "Jay Script");
await p.fill("#contact-email", "jay@example.com");
await p.fill("#contact-message", "Question about hosting.");
await p.locator("#contact form button[type=submit]").click();
await p.getByText("Message sent.").waitFor();
console.log("contact inline success:", new URL(p.url()).pathname);
console.log("console errors/warnings:", logs.length ? logs : "none");
await browser.close();
